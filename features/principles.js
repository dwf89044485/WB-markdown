const content = `
<h2>原则指南</h2>
<p>本项目的交互设计遵循以下核心原则，确保产品体验的一致性与高质量。</p>

<h3>1. 即时反馈</h3>
<p>用户每次操作后，系统应在 500ms 内给出明确反馈。反馈形式包括：状态变化、视觉动效、结果展示。避免让用户等待时产生不确定感。</p>

<h3>2. 渐进披露</h3>
<p>信息按层级逐步展开，从结果摘要到执行过程，再到原始细节。用户按需深入，不被一次性呈现的复杂信息所淹没。</p>
<ul>
  <li><strong>L1 结果层</strong>：展示最终结论或产物</li>
  <li><strong>L2 过程层</strong>：展示执行步骤与工具调用</li>
  <li><strong>L3 浮层详情层</strong>：通过 Sheet 浮层展示扩展信息</li>
  <li><strong>L4 原始细节层</strong>：展示完整的原始数据与日志</li>
</ul>

<h3>3. 一致性</h3>
<p>同类交互使用相同的视觉模式与操作方式。工具调用节点统一使用状态标签行，代码块统一使用卡片容器，浮层统一使用底部 Sheet。减少用户的认知负担。</p>

<h3>4. 容错与可逆</h3>
<p>所有关键操作应可撤销或可修正。提供明确的取消路径，避免用户陷入无法回退的状态。错误状态应有清晰的提示与恢复指引。</p>

<h3>5. 信息密度控制</h3>
<p>单屏信息量控制在用户可快速理解的范围内。长内容自动折叠（如代码块超过 280px 高度），通过「查看全部」等方式按需展开。避免信息过载。</p>

<h3>6. 设备自适应</h3>
<p>界面布局根据可用宽度自动调整：宽屏（>1200px）采用三栏布局，中屏（600-1200px）自动隐藏侧栏，窄屏（<600px）切换为底部 Sheet。确保在不同设备上均有良好的使用体验。</p>
`;

